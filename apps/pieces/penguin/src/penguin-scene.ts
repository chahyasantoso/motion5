/** The beak springs to each `mouthOpen` sample; a slower spring of the same samples is how lively the talk is. */
const mouth = follow({ start: 0, on: { mouthOpen: "value" }, stiffness: 1600, damping: 72 });
const liveliness = follow({ start: 0, on: { mouthOpen: "value" }, stiffness: 40, damping: 13 });
/** A blink is three samples long, so its spring is stiff enough to shut the lids inside them. */
const blink = follow({ start: 0, on: { blink: "value" }, stiffness: 4000, damping: 126 });

const clamp01 = (value: number): number => Math.min(1, Math.max(0, value));
const wave = (ms: number, periodMs: number, phase = 0): number =>
  Math.sin((2 * Math.PI * ms) / periodMs + phase);

/** The swell and the penguin's sway die away as the talk ends, so the piece comes to rest. */
const CALM_FROM = 7200;
const CALM_MS = 1000;
const calming = span(CALM_FROM, CALM_FROM + CALM_MS);

/** The snow's own clock: it slows with the calming and hangs still at the end, like a snow globe set down. */
function snowClock(ms: number): number {
  const into = clamp01((ms - CALM_FROM) / CALM_MS);
  if (into === 0) return ms;
  return CALM_FROM + CALM_MS * (into / 2 + Math.sin(Math.PI * into) / (2 * Math.PI));
}

interface Flake {
  readonly x: number;
  readonly spawn: number;
  readonly speed: number;
  readonly land: number;
  readonly drift: number;
  readonly sway: number;
  readonly phase: number;
  readonly size: number;
  readonly lifeMs: number;
}

interface FlakeLayer {
  readonly seed: number;
  readonly count: number;
  readonly speed: readonly [number, number];
  readonly land: readonly [number, number];
  readonly size: readonly [number, number];
}

const TOP = 4;
const MELT_MS = 450;

/** Flakes start inside the frame unseen, fade in as they fall, and melt where they land; none crosses an edge. */
function flakesOf(layer: FlakeLayer): readonly Flake[] {
  const random = seeded(layer.seed);
  const between = ([low, high]: readonly [number, number]): number => mix(low, high, random());
  const storyMs = STORY_MS;
  return Array.from({ length: layer.count }, (_, index) => {
    const speed = between(layer.speed);
    const land = between(layer.land);
    const lifeMs = ((land - TOP) / speed) * 1000;
    const drift = mix(10, 70, random());
    const sway = mix(5, 14, random());
    const slot = (storyMs + lifeMs) / layer.count;
    return {
      x: mix(20 + sway, 1250 - drift - sway, random()),
      spawn: -lifeMs + (index + random()) * slot,
      speed,
      land,
      drift,
      sway,
      phase: random() * 2 * Math.PI,
      size: between(layer.size),
      lifeMs,
    };
  });
}

function flakePose(flake: Flake, ms: number, opacity: number): Pose2d {
  const age = ms - flake.spawn;
  const airborne = Math.min(Math.max(age, 0), flake.lifeMs);
  const fall = (airborne * flake.speed) / 1000;
  const melt = clamp01((age - flake.lifeMs) / MELT_MS);
  const along = fall / (flake.land - TOP);
  return {
    x: flake.x + flake.drift * along + flake.sway * Math.sin(flake.phase + airborne / 650),
    y: TOP + fall,
    scale: flake.size * (1 - 0.6 * melt),
    opacity: opacity * clamp01(fall / 50) * (1 - melt),
  };
}

