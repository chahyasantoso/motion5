const LEAN = -6;
const TUCK = -10;
const STEP = { angle: 6, count: 2, sink: 4 };

const leanOf = (time: Time): number => {
  const settling = beats.settle.of(time, springEase({ stiffness: 140, damping: 11 })).progress;
  const leaning = beats.lean.of(time, ease.sineInOut).progress;
  return LEAN * leaning * (1 - settling);
};

const rollOf = (time: Time): number =>
  (waddle(STEP, beats.waddle.of(time)).rotation ?? 0) + leanOf(time);
const lagOf = trail((time: Time) => rollOf(time), { stiffness: 150, damping: 15, rest: 0.25 });

const turnAbout = (pivot: Pivot, about: Pivot, degrees: number): Pose2d => {
  const r = (degrees * Math.PI) / 180;
  const dx = pivot.x - about.x;
  const dy = pivot.y - about.y;
  return {
    x: about.x + dx * Math.cos(r) - dy * Math.sin(r) - pivot.x,
    y: about.y + dx * Math.sin(r) + dy * Math.cos(r) - pivot.y,
    rotation: degrees,
  };
};

const armPose = (arm: typeof left, roll: number, sink: number, turn: number): Pose2d => {
  const rest = arm.rest;
  const base = rest.base ?? { x: CORE.x, y: CORE.y, rotation: 0 };
  const pose = chainFromRest(arm.chain, rest, {
    base: { ...base, y: base.y + sink },
    rotations: {
      ...rest.rotations,
      core: (rest.rotations?.["core"] ?? 0) + roll,
      shoulder: (rest.rotations?.["shoulder"] ?? 0) + turn,
    },
  });
  return pose.shoulder;
};

// A pose that changes nothing is written as none, so a part at rest draws exactly as the artwork does.
const NONE = 1e-6;
const asDrawn = (pose: Pose2d): Pose2d =>
  Math.abs(pose.x ?? 0) < NONE &&
  Math.abs(pose.y ?? 0) < NONE &&
  Math.abs(pose.rotation ?? 0) < NONE &&
  Math.abs((pose.scaleX ?? 1) - 1) < NONE &&
  Math.abs((pose.scaleY ?? 1) - 1) < NONE
    ? {}
    : pose;

export const scene = (time: Time, events: Events) => {
  const step = waddle(STEP, beats.waddle.of(time));
  const roll = (step.rotation ?? 0) + leanOf(time);
  const sink = step.y ?? 0;
  const swing = 0.8 * (lagOf(time, events) - roll);
  const hold =
    beats.lean.of(time, ease.sineInOut).progress *
    (1 - beats.settle.of(time, ease.sineInOut).progress);
  const wave = handWave(
    { lift: -195, swing: 14, count: 2, reach: 0.72, fold: 0.6 },
    beats.wave.of(time),
  );

  const core = asDrawn({ rotation: roll, y: sink });
  const flipperLeft = asDrawn(armPose(left, roll, sink, swing + TUCK * hold));
  const flipperRight = asDrawn(
    combine([
      armPose(right, roll, sink, swing + (wave.rotation ?? 0)),
      { scaleX: wave.scaleX ?? 1, scaleY: wave.scaleY ?? 1 },
    ]),
  );
  const feet = asDrawn(turnAbout(FEET, roll < 0 ? HEEL_LEFT : HEEL_RIGHT, 0.4 * roll));

  return {
    feet,
    feetShade: feet,
    body: core,
    belly: core,
    bodyShade: core,
    flipperLeftLining: flipperLeft,
    flipperLeft,
    flipperRightLining: flipperRight,
    flipperRight,
    glassesLeft: core,
    glassesRight: core,
    lensLeft: core,
    lensRight: core,
    glintLeft: core,
    glintRight: core,
    glintBridge: core,
    nose: core,
    pupilLeft: core,
    sparkLeft: core,
    pupilRight: core,
    sparkRight: core,
  };
};
